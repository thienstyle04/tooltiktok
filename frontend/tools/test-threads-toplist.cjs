const assert = require('node:assert/strict');
const esbuild = require('../../backend/node_modules/esbuild');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const result = esbuild.buildSync({ entryPoints: [path.join(root, 'frontend/lib/pageMarkup.js')], bundle: true, write: false, platform: 'node', format: 'cjs' });
const moduleObject = { exports: {} };
vm.runInNewContext(result.outputFiles[0].text, { module: moduleObject, exports: moduleObject.exports, require, console });
const { renderCoverPage, renderListPage } = moduleObject.exports;
const cover = { type: 'cover', layoutVariant: 'threads-toplist-cover', title: 'Top list các địa điểm Đà Lạt', subtitle: '', backgroundImage: '' };
const list = { id: 'threads-toplist-dalat-main', pages: [cover] };
const coverHtml = renderCoverPage(cover, 0, 4, list.id, [], list);
assert(coverHtml.includes('/templates/threads-toplist-door.png'));
assert(coverHtml.includes('Top list các địa điểm Đà Lạt'));
assert(!coverHtml.includes('go.freelancer'));
const page = { type: 'list', layoutVariant: 'threads-toplist-page', chipText: 'Quán ăn', title: 'Quán ăn', subtitle: '', backgroundImage: '', items: Array.from({ length: 5 }, (_, i) => ({ label: String(i + 1), name: `Địa điểm ${i + 1} <test>`, metaPrimary: `Địa chỉ ${i + 1}`, imageUrl: '' })) };
const html = renderListPage(page, 1, 4, list.id, [], { ...list, pages: [cover, page] });
assert.equal((html.match(/threads-toplist-place/g) || []).length, 5);
assert.equal((html.match(/&lt;test&gt;/g) || []).length, 5);
assert(!html.includes('threads-toplist-number'), 'Venue numbering must not appear in previews or exports');
assert(!html.includes('<img') && !html.includes('go.freelancer'));
console.log('PASS threads toplist markup: local original cover, editable text-only places, escaped content');
