const assert = require('node:assert/strict');
const esbuild = require('../../backend/node_modules/esbuild');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const result = esbuild.buildSync({ stdin: { contents: "export {parseThreadsBudgetAmount,threadsBudgetTotals,renderThreadsBudgetPage} from './frontend/lib/threadsBudget'; export {renderListPage} from './frontend/lib/pageMarkup';", resolveDir: root }, bundle: true, write: false, platform: 'node', format: 'cjs' });
const mod = { exports: {} };
new Function('module', 'exports', 'require', result.outputFiles[0].text)(mod, mod.exports, require);
const { parseThreadsBudgetAmount, threadsBudgetTotals, renderThreadsBudgetPage, renderListPage } = mod.exports;
for (const [raw, expected] of [['610,000 đ',610000],['223.000 đ',223000],['200.000 đ/người',200000],['1,2tr',1200000],['65k',65000],['Free',0],['',null],['~50k',null],['50k-70k',null],['Giá nguồn: 200.000 đ/người; chưa rõ tổng 2 đêm',null]]) {
  assert.equal(parseThreadsBudgetAmount(raw), expected, raw);
}
const groups = ['Di chuyển','Lưu trú','Ngày 1','Ngày 2','Ngày 3'];
const prices = [['610.000 đ','223.000 đ'],['150.000 đ','640.000 đ'],['12.000 đ','18.000 đ','65.000 đ','80.000 đ'],['57.000 đ','42.750 đ','47.000 đ','98.000 đ'],['234.000 đ','30.000 đ','30.000 đ','50.000 đ']];
const items = groups.flatMap((group, i) => prices[i].map((price, j) => ({ label: group, name: `Chi tiết ${i}-${j} <test>`, metaSecondary: price })));
const totals = threadsBudgetTotals(items);
assert.equal(totals.groups['Di chuyển'].amount, 833000);
assert.equal(totals.groups['Lưu trú'].amount, 790000);
assert.equal(totals.amount, 2386750);
assert.equal(totals.missingCount, 0);
assert.equal(totals.complete, true);
const page = { items, subtitle: '' };
const html = renderThreadsBudgetPage(page, 0, 'test');
assert(html.includes('2.386.750 đ'));
assert(html.includes('833.000 đ'));
assert(html.includes('790.000 đ'));
assert(html.includes('Tổng chi phí'));
assert(!html.includes('Tạm tính'));
assert(html.includes('&lt;test&gt;'));
assert(!/<img\b|placeholder/i.test(html));
const dispatchedPage = { ...page, type: 'list', layoutVariant: 'itinerary-note-threads-budget', title: 'Bảng chi phí', backgroundImage: '/assets/drive-file?id=STALE_IMAGE_1234567890', items: items.map(item => ({ ...item, imageUrl: '/assets/drive-file?id=STALE_ITEM_1234567890' })) };
const dispatchedHtml = renderListPage(dispatchedPage, 0, 1, 'test', [], { pages: [dispatchedPage] });
assert(dispatchedHtml.includes('<table class="threads-budget-table">'), 'The public page renderer must dispatch to the table renderer');
assert(!/page-card|page-shell-bg|<img\b|STALE_IMAGE|STALE_ITEM/.test(dispatchedHtml), 'The public renderer must not fall back to photo cards');
items[0].metaSecondary = '';
const partial = threadsBudgetTotals(items);
assert.equal(partial.amount, 1776750);
assert.equal(partial.missingCount, 1);
assert.equal(partial.complete, false);
const partialHtml = renderThreadsBudgetPage(page, 0, 'test');
assert(partialHtml.includes('1.776.750 đ'));
assert(partialHtml.includes('Tạm tính · còn 1 khoản chưa có giá'));
assert(partialHtml.includes('Tạm tính · thiếu 1 khoản'));
items[2].metaSecondary = 'Giá nguồn: 200.000 đ/người; chưa rõ tổng 2 đêm';
const referenceOnly = threadsBudgetTotals(items);
assert.equal(referenceOnly.amount, 1626750, 'Reference price must not be counted as a two-night total');
assert.equal(referenceOnly.missingCount, 2);
assert(renderThreadsBudgetPage(page, 0, 'test').includes('Giá nguồn: 200.000 đ/người; chưa rõ tổng 2 đêm'));
const allMissingItems = items.map(item => ({ ...item, metaSecondary: '' }));
assert.equal(threadsBudgetTotals(allMissingItems).amount, null);
assert(renderThreadsBudgetPage({ ...page, items: allMissingItems }, 0, 'test').includes('Chưa có giá'));
console.log('PASS: public page renderer uses the expense table, full/partial totals, missing price, escaped text, no photo cards');
