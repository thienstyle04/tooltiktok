import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {coverReviewError,coverApprovalToken} from '../lib/spotlightCoverReview.mjs';
const require=createRequire(import.meta.url), esbuild=require('esbuild');
const front=path.resolve(import.meta.dirname,'..');
const code=await esbuild.build({entryPoints:[path.join(front,'lib/pageMarkup.js')],bundle:true,write:false,platform:'node',format:'cjs'});
const Module=require('node:module'), mod=new Module('spotlight-render-test'); mod._compile(code.outputFiles[0].text,'spotlight-render-test.cjs');
const {renderCoverPage,renderListPage}=mod.exports;
const page={type:'cover',title:'Địa điểm xanh giữa rừng',subtitle:'',backgroundImage:'/assets/drive-file?id=a',coverImages:['/assets/drive-file?id=a'],layoutVariant:'spotlight-v4-cover',titlePlacement:'center'};
const old={id:'spotlight-v4-old',pages:[page]};
assert.ok(!renderCoverPage(page,0,1,old.id,[],old).includes('spotlight-design-1'));
const next={...old,spotlightDesignRevision:1,pages:[{...page,spotlightDesignRevision:1}],coverReview:{topic:'green',approvedSourceIds:[],warnings:[]}};
assert.ok(coverReviewError(next));
next.pages[0].coverApproval=coverApprovalToken(next.pages[0]); assert.equal(coverReviewError(next),'');
next.pages[0].title='Cà phê nào ở Đà Lạt'; assert.ok(coverReviewError(next));
assert.equal(coverReviewError(old),'');
assert.ok(coverReviewError({...next,pages:[{...next.pages[0],layoutVariant:'spotlight-v2-cover',title:'Đà Lạt'}]}));
assert.ok(renderCoverPage(next.pages[0],0,1,next.id,[],next).includes('spotlight-design-1'));
assert.ok(renderCoverPage(next.pages[0],0,1,next.id,[],next).includes('spotlight-v2-place-center'));
const venue={type:'list',title:'Quán',items:[{name:'Quán',rawName:'Quán',metaPrimary:'Địa chỉ',metaSecondary:'Open: 10:00 - 20:00 · Giá: 50.000 đ',imageUrl:'/assets/drive-file?id=a'}],layoutVariant:'spotlight-v2',spotlightDesignRevision:1};
assert.ok(!renderListPage(venue,1,2,'spotlight-v2-test',[],{}).includes('Giá:'));
assert.ok(renderListPage({...venue,spotlightDesignRevision:undefined},1,2,'spotlight-v2-old',[],{}).includes('Giá:'));
await esbuild.build({entryPoints:[path.join(front,'components/DeckStudio.js')],bundle:true,write:false,platform:'browser',loader:{'.js':'jsx'}});
console.log('Spotlight renderer, cover gate and UI bundle: PASS');
